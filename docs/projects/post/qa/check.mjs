import assert from 'node:assert/strict';
import {createRoute, passage,tide} from '../route.mjs';
assert.deepEqual([3,4,7,8].map(tide),['high','low','low','high']);
assert.equal(passage('bell','east',3).duration,3);
assert.equal(passage('east','bell',6).ok,false);
assert.equal(passage('inlet','home',8).ok,false);
const a=createRoute();
for(const port of ['bell','east','buoy','home'])a.append(port);
assert.deepEqual(a.forecast().map(s=>s.minute),[3,6,10,12]);
a.launch();a.advance(1.5);assert.equal(a.getState().at,'home');
assert.ok(Math.abs(a.position().x-(-2.315))<1e-9);
a.advance(20);assert.deepEqual(a.getState().delivered,['bell','east']);assert.equal(a.getState().time,12);
assert.equal(a.getState().mode,'done');a.reset();
for(const port of ['buoy','east','bell'])a.append(port);
assert.deepEqual(a.getState().plan,['buoy','east']);
a.append('wait');a.append('wait');a.append('bell');a.append('home');
a.launch();for(let i=0;i<140;i++)a.advance(.1);
assert.equal(a.getState().mode,'done');assert.equal(a.getState().time,14);
a.reset();a.append('bell');a.append('east');a.launch();a.advance(.7);a.stop();a.advance(4);
assert.equal(a.getState().mode,'plan');assert.equal(a.getState().at,'bell');
assert.deepEqual(a.getState().plan,[]);console.log('two complete itineraries, tide boundaries, midpoint, stop, reset: pass');
